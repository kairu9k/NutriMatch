function norm(s) {
  return String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()
}

// Search-only shortcuts for abbreviations RNDs type; they never change the
// sheet's wording, they just find it ("hba1c" → "Hemoglobin A1c (HgbA1c)").
const SEARCH_ALIASES = {
  hba1c: 'a1c', fbs: 'glucose fasting', rbs: 'glucose casual', bp: 'blood pressure', sbp: 'blood pressure systolic',
  dbp: 'blood pressure diastolic', hr: 'heart rate', bmi: 'body mass index', hgb: 'hemoglobin', hb: 'hemoglobin',
  hct: 'hematocrit', tg: 'triglycerides', egfr: 'glomerular filtration', gfr: 'glomerular filtration', wc: 'waist circumference',
  k: 'potassium', na: 'sodium', alb: 'albumin', crea: 'creatinine', chol: 'cholesterol',
}

// Picker groups for a search: every word of the query must appear in the term
// or its group's name. Empty query = every group.
export function signGroups(query) {
  const words = norm(query).split(' ').filter(Boolean).flatMap(w => (SEARCH_ALIASES[w] || w).split(' '))
  const label = Object.fromEntries(SIGN_GROUPS.map(g => [g.code, g.label]))
  const hit = s => words.every(w => norm(`${s.t} ${label[s.g]}`).includes(w))
  return SIGN_GROUPS
    .map(g => ({ key: g.code, label: g.label, domain: g.code.slice(0, 2), items: SIGNS.filter(s => s.g === g.code && hit(s)) }))
    .filter(g => g.items.length)
}
