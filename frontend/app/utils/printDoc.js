// Print (or "Save as PDF") a receipt / statement: opens a clean, branded
// page in a new window and starts the browser's print dialog. Used by the
// client's receipt and the RND's payout statement.

const esc = v => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]))

/**
 * @param {object} doc
 * @param {string} doc.title       e.g. "Official receipt"
 * @param {string} doc.number      e.g. "INV-0036"
 * @param {Array<[string, string]>} doc.rows  label/value pairs
 * @param {Array<Array<string>>} [doc.table]  optional rows; first row is the header
 * @param {[string, string]} doc.total        e.g. ["Total paid", "₱800.00"]
 * @param {string} [doc.note]
 */
export function printDocument({ title, number, rows = [], table = null, total, note = '' }) {
  const w = window.open('', '_blank', 'width=720,height=900')
  if (!w) return false
  const tableHtml = table && table.length > 1
    ? `<table class="items"><thead><tr>${table[0].map(h => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${
      table.slice(1).map(r => `<tr>${r.map(c => `<td>${esc(c)}</td>`).join('')}</tr>`).join('')}</tbody></table>`
    : ''
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${esc(number)} · NutriMatch</title>
<style>
  * { box-sizing: border-box; }
  body { font-family: Arial, Helvetica, sans-serif; color: #1a3a1a; margin: 0; padding: 36px; }
  .head { display: flex; justify-content: space-between; align-items: flex-start; border-bottom: 3px solid #00382a; padding-bottom: 16px; margin-bottom: 22px; }
  .brand { font-family: Georgia, 'Times New Roman', serif; font-size: 24px; font-weight: bold; color: #00382a; }
  .brand span { color: #b8860b; }
  .sub { font-size: 11px; letter-spacing: 0.12em; color: #6a7a6a; text-transform: uppercase; margin-top: 4px; }
  .doc { text-align: right; }
  .doc h1 { font-family: Georgia, serif; font-size: 20px; margin: 0; }
  .doc p { margin: 4px 0 0; color: #4a5a4a; font-size: 13px; }
  dl { display: grid; grid-template-columns: 180px 1fr; gap: 0; margin: 0 0 18px; border: 1px solid #dfe5df; border-radius: 8px; overflow: hidden; }
  dt, dd { margin: 0; padding: 10px 14px; font-size: 13px; border-bottom: 1px solid #eef1ee; }
  dt { color: #6a7a6a; background: #fafbfa; }
  dd { font-weight: bold; }
  table.items { width: 100%; border-collapse: collapse; font-size: 12px; margin: 0 0 18px; }
  table.items th { text-align: left; color: #6a7a6a; border-bottom: 2px solid #dfe5df; padding: 8px 6px; }
  table.items td { border-bottom: 1px solid #eef1ee; padding: 8px 6px; }
  .total { display: flex; justify-content: space-between; align-items: center; background: #f2f7f3; border-radius: 8px; padding: 14px 16px; font-size: 15px; }
  .total strong { font-family: Georgia, serif; font-size: 22px; }
  .note { font-size: 12px; color: #6a7a6a; margin: 16px 0 0; line-height: 1.5; }
  .foot { margin-top: 30px; border-top: 1px solid #dfe5df; padding-top: 12px; font-size: 11px; color: #8a9a8a; line-height: 1.5; }
  @media print { body { padding: 0; } }
</style></head><body>
  <div class="head">
    <div><div class="brand">Nutri<span>Match</span></div><div class="sub">Clinical Nutrition Consultation</div></div>
    <div class="doc"><h1>${esc(title)}</h1><p>${esc(number)}</p><p>Printed ${esc(new Date().toLocaleDateString('en-PH', { month: 'long', day: 'numeric', year: 'numeric' }))}</p></div>
  </div>
  <dl>${rows.map(([k, v]) => `<dt>${esc(k)}</dt><dd>${esc(v)}</dd>`).join('')}</dl>
  ${tableHtml}
  ${total ? `<div class="total"><span>${esc(total[0])}</span><strong>${esc(total[1])}</strong></div>` : ''}
  ${note ? `<p class="note">${esc(note)}</p>` : ''}
  <div class="foot">Generated by NutriMatch. Payments are processed by PayMongo. Your personal and health information is protected under the Data Privacy Act of 2012 (RA 10173).</div>
  <script>window.onload = function () { window.focus(); window.print(); }<\/script>
</body></html>`)
  w.document.close()
  return true
}
